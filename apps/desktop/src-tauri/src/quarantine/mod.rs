//! The quarantine folder: where approved cleanups move items, and from where they are put
//! back or, after a separate confirmation, permanently deleted.
//!
//! Safety rules (ADR-003, ADR-012):
//! - Items move by a same-volume rename that never replaces anything (`fsops`). An item on
//!   another volume is refused; nothing is ever copied and then deleted, so a failed move
//!   leaves the item exactly where it was.
//! - Every step opens folders from `/` one component at a time without following symlinks,
//!   checks the item's identity (device and inode, which a rename keeps) before acting, and
//!   checks it again afterwards.
//! - Restores never overwrite: an existing entry at the original place blocks the restore.
//! - Nothing is deleted except by an explicit permanent delete of a held item, and only
//!   inside the quarantine folder. Kleari never empties quarantine on its own.

