/// Name of the quarantine folder inside the app's data folder.
pub const FOLDER_NAME: &str = "Quarantine";
const FOLDER_C_NAME: &CStr = c"Quarantine";

/// What identifies an item across a rename: its volume, inode and whether it is a folder.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Identity {
    pub dev: u64,
    pub ino: u64,
    pub is_dir: bool,
}

impl Identity {
    pub fn of(stat: &FileStat) -> Self {
        Self {
            dev: stat.dev,
            ino: stat.ino,
            is_dir: stat.is_dir(),
        }
    }

    fn matches(self, stat: &FileStat) -> bool {
        !stat.is_symlink()
            && stat.dev == self.dev
            && stat.ino == self.ino
            && stat.is_dir() == self.is_dir
    }
}

/// Whether a held item is in the quarantine folder.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Presence {
    Held,
    Absent,
    Unknown,
}

/// Why a filesystem step didn't happen. Nothing was changed, except for `Unconfirmed`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Failure {
    /// macOS refused access (privacy permission or file permissions).
    NeedsAccess,
    /// It isn't there any more.
    Missing,
    /// It is a different item now (replaced, or swapped for a symlink).
    Changed,
    /// It is on another volume than the quarantine folder.
    OtherVolume,
    /// Something already exists at the destination.
    Exists,
    /// The folder it belongs in is gone or can't be opened safely.
    ParentUnavailable,
    /// The quarantine folder itself can't be opened or created safely.
    StoreUnavailable,
    /// The rename happened, but what is now in quarantine couldn't be checked. The item may
    /// well be in quarantine; it must not be reported or recorded as left in place.
    Unconfirmed,
    /// Any other error.
    Other,
}

fn failure(error: &io::Error) -> Failure {
    match error.raw_os_error() {
        Some(libc::EACCES | libc::EPERM) => Failure::NeedsAccess,
        Some(libc::ENOENT) => Failure::Missing,
        Some(libc::EXDEV) => Failure::OtherVolume,
        Some(libc::EEXIST | libc::ENOTEMPTY) => Failure::Exists,
        _ => match error.kind() {
            io::ErrorKind::CrossesDevices => Failure::OtherVolume,
            io::ErrorKind::InvalidData => Failure::Changed,
            _ => Failure::Other,
        },
    }
}

/// An absolute path's folder and final name, or `None` for `/`, a relative path or one with
/// `.`/`..` components.
pub fn split(path: &Path) -> Option<(&Path, CString)> {
    use std::path::Component;
    if !path.is_absolute()
        || path
            .components()
            .any(|component| matches!(component, Component::ParentDir | Component::CurDir))
    {
        return None;
    }
    let name = path.file_name()?;
    Some((path.parent()?, CString::new(name.as_bytes()).ok()?))
}

fn c_name(text: &str) -> Option<CString> {
    // Batch and item IDs are generated by Kleari from hex digits and dashes.
    (!text.is_empty()
        && text
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() || byte == b'-'))
    .then(|| CString::new(text).ok())
    .flatten()
}

/// The quarantine folder, `<data folder>/Quarantine`.
#[derive(Debug, Clone)]
pub struct Store {
    data_folder: PathBuf,
}

impl Store {
    pub fn new(data_folder: PathBuf) -> Self {
        Self { data_folder }
    }

    pub fn path(&self) -> PathBuf {
        self.data_folder.join(FOLDER_NAME)
    }

    /// Where an item is kept, for showing it in Finder. `None` unless both IDs are names
    /// Kleari makes (hex digits and dashes, one path component each), so a malformed history
    /// can't point it outside the quarantine folder.
    pub fn reveal_path(&self, batch_id: &str, item_id: &str) -> Option<PathBuf> {
        c_name(batch_id)?;
        c_name(item_id)?;
        Some(self.path().join(batch_id).join(item_id))
    }

    /// Where an item is kept (tests build paths from IDs they chose).
    #[cfg(test)]
    pub fn item_path(&self, batch_id: &str, item_id: &str) -> PathBuf {
        self.path().join(batch_id).join(item_id)
    }

    /// Opens the quarantine folder (creating it owner-only if needed), with no symlink
    /// anywhere on its path. Returns it and its volume.
    fn open_root(&self) -> Result<(DirHandle, u64), Failure> {
        let (data, dev) = open_absolute(&self.data_folder).ok_or(Failure::StoreUnavailable)?;
        let dir = open_or_make(&data, FOLDER_C_NAME, dev).map_err(|_| Failure::StoreUnavailable)?;
        Ok((dir, dev))
    }

    /// The volume the quarantine folder is on.
    pub fn volume(&self) -> Option<u64> {
        self.open_root().ok().map(|(_, dev)| dev)
    }

    /// Moves the item at `original` into batch `batch_id` as `item_id`. `expected` is the
    /// identity checked when the preview was approved; the item must still have it. Returns
    /// the identity of what was moved (checked again in the quarantine folder).
    pub fn move_in(
        &self,
        original: &Path,
        expected: Identity,
        batch_id: &str,
        item_id: &str,
    ) -> Result<Identity, Failure> {
        let (parent_path, name) = split(original).ok_or(Failure::ParentUnavailable)?;
        let batch_name = c_name(batch_id).ok_or(Failure::Other)?;
        let item_name = c_name(item_id).ok_or(Failure::Other)?;
        let (parent, _) = open_absolute(parent_path).ok_or(Failure::ParentUnavailable)?;
        let stat = parent.stat_child(&name).map_err(|error| failure(&error))?;
        if !expected.matches(&stat) {
            return Err(Failure::Changed);
        }
        let (root, store_dev) = self.open_root()?;
        if stat.dev != store_dev {
            return Err(Failure::OtherVolume);
        }
        let batch =
            open_or_make(&root, &batch_name, store_dev).map_err(|_| Failure::StoreUnavailable)?;
        fsops::rename_exclusive(&parent, &name, &batch, &item_name)
            .map_err(|error| failure(&error))?;
        // From here the rename has happened: nothing below may report that the item stayed.
        // If what was moved can't be checked, the outcome is `Unconfirmed`.
        let moved = batch
            .stat_child(&item_name)
            .map_err(|_| Failure::Unconfirmed)?;
        // A swap between the check and the rename would have moved something else: put that
        // back. If it can't be put back it stays in quarantine and its real identity is
        // returned, so the caller records what is actually held.
        if !expected.matches(&moved)
            && fsops::rename_exclusive(&batch, &item_name, &parent, &name).is_ok()
        {
            let at_original = parent.stat_child(&name).ok();
            let slot_empty = batch
                .stat_child(&item_name)
                .is_err_and(|error| error.raw_os_error() == Some(libc::ENOENT));
            return Err(settle_move_rollback(
                expected,
                at_original.as_ref(),
                slot_empty,
            ));
        }
        Ok(Identity::of(&moved))
    }

    /// Whether the held item is in the quarantine folder with its recorded identity.
    #[cfg(test)]
    pub fn holds(&self, batch_id: &str, item_id: &str, identity: Identity) -> bool {
        self.presence(batch_id, item_id, identity) == Presence::Held
    }

    /// Whether the item is held, definitely absent, or can't be told (the quarantine folder
    /// couldn't be opened, access was refused, or something else is under its name). Only
    /// `Absent` lets a caller conclude a move didn't happen.
    pub fn presence(&self, batch_id: &str, item_id: &str, identity: Identity) -> Presence {
        match self.held_entry(batch_id, item_id) {
            Ok((_, _, stat)) if identity.matches(&stat) => Presence::Held,
            Ok(_) => Presence::Unknown,
            Err(Failure::Missing) => Presence::Absent,
            Err(_) => Presence::Unknown,
        }
    }

    fn held_entry(
        &self,
        batch_id: &str,
        item_id: &str,
    ) -> Result<(DirHandle, CString, FileStat), Failure> {
        let batch_name = c_name(batch_id).ok_or(Failure::Missing)?;
        let item_name = c_name(item_id).ok_or(Failure::Missing)?;
        let (root, dev) = self.open_root()?;
        let batch_stat = root
            .stat_child(&batch_name)
            .map_err(|error| failure(&error))?;
        if !batch_stat.is_dir() || batch_stat.dev != dev {
            return Err(Failure::Missing);
        }
        let (batch, opened) = root
            .open_child(&batch_name)
            .map_err(|error| failure(&error))?;
        if opened.ino != batch_stat.ino || opened.dev != batch_stat.dev {
            return Err(Failure::Changed);
        }
        let stat = batch
            .stat_child(&item_name)
            .map_err(|error| failure(&error))?;
        Ok((batch, item_name, stat))
    }

    /// Whether the entry at `original` is the item with `identity` (a restore finished),
    /// `None` if its folder can't be opened safely.
    fn at_original(original: &Path, identity: Identity) -> Option<bool> {
        let (parent_path, name) = split(original)?;
        let (parent, _) = open_absolute(parent_path)?;
        match parent.stat_child(&name) {
            Ok(stat) => Some(identity.matches(&stat)),
            Err(error) if error.raw_os_error() == Some(libc::ENOENT) => Some(false),
            Err(_) => None,
        }
    }

    /// What became of an item a previous run left `moving` or `restoring`, from what the
    /// folders show now. `None` when that can't be told, so the record is kept for later and
    /// never concluded from an error. The original place is only looked at when
    /// `original_in_scope` (the recorded path is one its category may come from).
    pub fn resolve_interrupted(
        &self,
        item: &crate::persistence::ItemRecord,
        original_in_scope: bool,
    ) -> Option<crate::persistence::ItemState> {
        use crate::persistence::ItemState;
        let identity = Identity {
            dev: item.dev,
            ino: item.ino,
            is_dir: item.is_dir,
        };
        let held = self.presence(&item.batch_id, &item.id, identity);
        match (item.state, held) {
            (ItemState::Moving | ItemState::Restoring, Presence::Held) => Some(ItemState::Held),
            (ItemState::Moving, Presence::Absent) => Some(ItemState::NotMoved),
            // Gone from quarantine: restored only if the item is back at its original place.
            (ItemState::Restoring, Presence::Absent) => (original_in_scope
                && Self::at_original(&item.original, identity) == Some(true))
            .then_some(ItemState::Restored),
            _ => None,
        }
    }

    /// Whether something now exists at `original` (a restore would be blocked), `None` if
    /// its folder can't be opened safely.
    pub fn original_taken(original: &Path) -> Option<bool> {
        let (parent_path, name) = split(original)?;
        let (parent, _) = open_absolute(parent_path)?;
        match parent.stat_child(&name) {
            Ok(_) => Some(true),
            Err(error) if error.raw_os_error() == Some(libc::ENOENT) => Some(false),
            Err(_) => None,
        }
    }

    /// Puts the held item back at `original`, refusing to replace anything there.
    pub fn restore(
        &self,
        batch_id: &str,
        item_id: &str,
        identity: Identity,
        original: &Path,
    ) -> Result<(), Failure> {
        let (batch, item_name, stat) = self.held_entry(batch_id, item_id)?;
        if !identity.matches(&stat) {
            return Err(Failure::Changed);
        }
        let (parent_path, name) = split(original).ok_or(Failure::ParentUnavailable)?;
        let (parent, _) = open_absolute(parent_path).ok_or(Failure::ParentUnavailable)?;
        fsops::rename_exclusive(&batch, &item_name, &parent, &name)
            .map_err(|error| failure(&error))?;
        // From here the rename has happened. What arrived must be the held item: a
        // replacement swapped in after the check is moved back into quarantine. If what
        // arrived can't be checked, or a replacement can't be moved back, the outcome is
        // `Unconfirmed` and the record is resolved from the folders at the next launch.
        let arrived = parent.stat_child(&name).map_err(|_| Failure::Unconfirmed)?;
        if !identity.matches(&arrived) {
            let in_batch = fsops::rename_exclusive(&parent, &name, &batch, &item_name)
                .ok()
                .and_then(|()| batch.stat_child(&item_name).ok());
            return Err(settle_restore_rollback(identity, in_batch.as_ref()));
        }
        drop(batch);
        self.remove_batch_if_empty(batch_id);
        Ok(())
    }

    /// Permanently deletes the held item from the quarantine folder.
    pub fn delete(&self, batch_id: &str, item_id: &str, identity: Identity) -> Result<(), Failure> {
        let (batch, item_name, stat) = self.held_entry(batch_id, item_id)?;
        if !identity.matches(&stat) {
            return Err(Failure::Changed);
        }
        // The walk checks the identity again itself, so a replacement put under the item's
        // name after this check is left alone. Any error during the walk, including an
        // entry vanishing part-way, means the delete didn't complete: it is never reported as
        // `Missing` (which callers read as "already gone") but as a failure, and the item
        // stays held. Only absence found before the walk (`held_entry`) is `Missing`.
        fsops::remove_tree(&batch, &item_name, identity).map_err(|error| {
            match failure(&error) {
                Failure::Missing => Failure::Other,
                other => other,
            }
        })?;
        drop(batch);
        self.remove_batch_if_empty(batch_id);
        Ok(())
    }

    /// Removes a batch folder once its last item has left. A batch that still holds anything
    /// stays; that is the normal case, not an error.
    fn remove_batch_if_empty(&self, batch_id: &str) {
        if let (Ok((root, _)), Some(name)) = (self.open_root(), c_name(batch_id)) {
            let _ = fsops::remove_empty_dir(&root, &name);
        }
    }
}

/// After a move put a swapped entry back: the move is settled as "not moved" (`Changed`) only
/// when the approved item itself is at its original place and quarantine holds nothing under
/// the item's name. Proving the swapped entry went back isn't enough: the approved item could
/// be anywhere. Otherwise `Unconfirmed`, and the record stays `moving`.
fn settle_move_rollback(
    expected: Identity,
    at_original: Option<&FileStat>,
    slot_empty: bool,
) -> Failure {
    if slot_empty && at_original.is_some_and(|stat| expected.matches(stat)) {
        Failure::Changed
    } else {
        Failure::Unconfirmed
    }
}

/// After a restore put a mismatched arrival back: the record goes back to held (`Changed`)
/// only when quarantine holds the recorded item itself under its name. Otherwise
/// `Unconfirmed`, and the record stays `restoring`.
fn settle_restore_rollback(recorded: Identity, in_batch: Option<&FileStat>) -> Failure {
    if in_batch.is_some_and(|stat| recorded.matches(stat)) {
        Failure::Changed
    } else {
        Failure::Unconfirmed
    }
}

/// Opens the folder `name` in `parent`, creating it if missing. It must be a real folder on
/// volume `dev` (not a symlink), with the identity `lstat` reported.
fn open_or_make(parent: &DirHandle, name: &CStr, dev: u64) -> io::Result<DirHandle> {
    let stat = match parent.stat_child(name) {
        Ok(stat) => stat,
        Err(error) if error.raw_os_error() == Some(libc::ENOENT) => {
            match fsops::make_dir(parent, name) {
                Ok(()) => {}
                // Created by another step in the meantime; checked below like any folder.
                Err(error) if error.raw_os_error() == Some(libc::EEXIST) => {}
                Err(error) => return Err(error),
            }
            parent.stat_child(name)?
        }
        Err(error) => return Err(error),
    };
    if !stat.is_dir() || stat.dev != dev {
        return Err(io::Error::from(io::ErrorKind::InvalidData));
    }
    let (dir, opened) = parent.open_child(name)?;
    if opened.dev != stat.dev || opened.ino != stat.ino {
        return Err(io::Error::from(io::ErrorKind::InvalidData));
    }
    Ok(dir)
}
